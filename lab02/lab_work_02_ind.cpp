/* Обчислити при заданих x, y, z:                                */
/*        pi - ln(1 + 3/(x^2+2)) + |x + y/2| - (x-4.2)(y+2.8)    */
/* a = cos^2 ---------------------------------------------------- */
/*         (2x^2 + 3y^2 + ln(1+|z|)) * sin((x+y)^2 + 1)          */
/*                                                               */
/* b = sqrt( lg(25 + (3y^2+x^2+1.43)/(4+sin(x/2)))               */
/*           * (4 + arctg((y-0.1x)/(z^2+8))) )                   */
/*****************************************************************/
#include <iostream>
#include <iomanip>
#include <cmath>
#include "../common_console.h"
using namespace std;

int main()
{
    console_utf8();
    const double pi = 3.14159265358979;
    double x, y, z;
    cout << " Введіть x, y, z: "; cin >> x >> y >> z;
    if (!cin) { cout << " Помилка введення\n"; return 1; }

    // ---- обчислення a через проміжні величини ----
    double a1 = pi - log(1 + 3 / (x * x + 2));            // pi - ln(1+3/(x^2+2))
    double a2 = fabs(x + y / 2);                          // |x + y/2|
    double a3 = (x - 4.2) * (y + 2.8);                    // (x-4.2)(y+2.8)
    double a4 = 2 * x * x + 3 * y * y + log(1 + fabs(z)); // перший множник знаменника
    double a5 = sin(pow(x + y, 2) + 1);                   // sin((x+y)^2+1)
    double den = a4 * a5;
    if (fabs(den) < 1e-12) { cout << " Знаменник дорівнює нулю - a не визначено\n"; return 1; }
    double a = pow(cos((a1 + a2 - a3) / den), 2);

    // ---- обчислення b ----
    double b1 = 25 + (3 * y * y + x * x + 1.43) / (4 + sin(x / 2)); // 4+sin>=3, ділення безпечне
    double b2 = log10(b1);
    double b3 = 4 + atan((y - 0.1 * x) / (z * z + 8));
    double b  = sqrt(b2 * b3);                            // b2>1, b3>0 - корінь визначений

    cout << fixed << setprecision(5);
    cout << "\n +------------------------------------------+\n";
    cout << " |  x = " << setw(12) << x << "                        |\n";
    cout << " |  y = " << setw(12) << y << "                        |\n";
    cout << " |  z = " << setw(12) << z << "                        |\n";
    cout << " +--------------------+---------------------+\n";
    cout << " | a1 = " << setw(13) << a1 << " | b1 = " << setw(14) << b1 << " |\n";
    cout << " | a2 = " << setw(13) << a2 << " | b2 = " << setw(14) << b2 << " |\n";
    cout << " | a3 = " << setw(13) << a3 << " | b3 = " << setw(14) << b3 << " |\n";
    cout << " | a4 = " << setw(13) << a4 << " |                     |\n";
    cout << " | a5 = " << setw(13) << a5 << " |                     |\n";
    cout << " +--------------------+---------------------+\n";
    cout << " | a  = " << setw(13) << a  << " | b  = " << setw(14) << b  << " |\n";
    cout << " +--------------------+---------------------+\n";
    return 0;
}
