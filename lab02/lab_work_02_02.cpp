/*  Бібліотека арифметичних функцій С++.             */
/*  Дано: x,y,z - змінні дійсного типу.              */
/*  Обчислити a=f1(x,y,z) та b=f2(x,y,z), вивести    */
/*  вхідні величини, проміжні величини і результати  */
/*  у вигляді таблиці.                               */
/*  Виправлено помилки методички: pow(a3,1/2) та     */
/*  pow(b3,1/3) давали pow(..,0)=1 через цілочисельне*/
/*  ділення; замінено на sqrt() та cbrt().           */
/*****************************************************/
#include <iostream>
#include <iomanip>
#include <cmath>
#include "../common_console.h"
using namespace std;

int main()
{
    console_utf8();
    const double pi = 3.14159265358979;
    double x, y, z;
    double a1, a2, a3, a4, a5, a;
    double b1, b2, b3, b4, b5, b;

    cout << " Введіть значення трьох дійсних змінних x y z:\n "; cin >> x >> y >> z;
    if (!cin) { cout << " Помилка введення\n"; return 1; }

    // Обчислення виразу a
    a1 = y / (2 + y * y + fabs(y * z));
    a2 = acos(a1);
    a3 = pi + x * x + pow(sin(y * z), 2);
    a4 = sqrt(a3);                       // було pow(a3, 1/2)
    a5 = log10(2 / (x * x + y * y + 1));
    a  = a2 * (a4 - a5);

    // Обчислення виразу b
    b1 = exp(-3 * x * x + y / 3 - z);
    b2 = pow(tan(x), 2);
    b3 = b2 / (1 + sin(pi * y / 2));
    b4 = cbrt(b3);                       // було pow(b3, 1/3)
    b5 = (x + y + z) / (x * y * z);
    b  = b1 + b4 - pow(b5, 2);

    cout << fixed << setprecision(3);
    cout << "\n Вхідні величини та результати обчислень:\n";
    cout << " +-----------------------------------+\n";
    cout << " |          Вхідні величини          |\n";
    cout << " +-----------------------------------+\n";
    cout << " | x = " << setw(10) << x << "                    |\n";
    cout << " | y = " << setw(10) << y << "                    |\n";
    cout << " | z = " << setw(10) << z << "                    |\n";
    cout << " +-----------------------------------+\n";
    cout << " |        Результати обчислень       |\n";
    cout << " +-----------------+-----------------+\n";
    cout << " | a1 = " << setw(10) << a1 << " | b1 = " << setw(10) << b1 << " |\n";
    cout << " | a2 = " << setw(10) << a2 << " | b2 = " << setw(10) << b2 << " |\n";
    cout << " | a3 = " << setw(10) << a3 << " | b3 = " << setw(10) << b3 << " |\n";
    cout << " | a4 = " << setw(10) << a4 << " | b4 = " << setw(10) << b4 << " |\n";
    cout << " | a5 = " << setw(10) << a5 << " | b5 = " << setw(10) << b5 << " |\n";
    cout << " | a  = " << setw(10) << a  << " | b  = " << setw(10) << b  << " |\n";
    cout << " +-----------------+-----------------+\n";
    return 0;
}
