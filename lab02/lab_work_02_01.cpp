/*  Лінійні обчислювальні процеси засобами мови С++  */
/*  Дано: r - радіус основи прямого кругового        */
/*  циліндра; h - висота циліндра.                   */
/*  Обчислити: sb = 2*pi*r*h - площу бічної поверхні;*/
/*  sp = sb + 2*pi*r*r - площу повної поверхні;      */
/*  v = pi*r*r*h - об'єм циліндра. Результати подати */
/*  у вигляді таблиці.                               */
/*  Під час налагодження виправлено помилки методички:*/
/*  sp=sb+2*pi*r*r*h -> sp=sb+2*pi*r*r;              */
/*  v=pi*r*h*h       -> v=pi*r*r*h;                  */
/*  <iostream.h>, clrscr(), getch() -> стандарт C++. */
/*****************************************************/
#include <iostream>
#include <iomanip>
#include <cmath>
#include "../common_console.h"
using namespace std;

int main()
{
    console_utf8();
    const double pi = 3.14159265358979; // константа pi
    double r;   // радіус основи циліндра
    double h;   // висота циліндра
    double sb;  // площа бічної поверхні
    double sp;  // площа повної поверхні
    double v;   // об'єм циліндра

    // Введення заданих величин
    cout << " Введіть радіус основи циліндра: "; cin >> r;
    cout << " Введіть висоту циліндра: ";        cin >> h;
    if (!cin || r <= 0 || h <= 0) { cout << " Помилка: r та h мають бути додатними числами\n"; return 1; }

    // Обчислення параметрів циліндра
    sb = 2 * pi * r * h;
    sp = sb + 2 * pi * r * r;
    v  = pi * r * r * h;

    // Друк результатів у вигляді таблиці
    cout << fixed << setprecision(3);
    cout << "\n Вхідні величини та результати обчислень:\n";
    cout << " +----------------------------+------------+\n";
    cout << " |        Вхідні величини     |            |\n";
    cout << " +----------------------------+------------+\n";
    cout << " | Радіус основи циліндра     |" << setw(11) << r  << " |\n";
    cout << " | Висота циліндра            |" << setw(11) << h  << " |\n";
    cout << " +----------------------------+------------+\n";
    cout << " |    Результати обчислень    |            |\n";
    cout << " +----------------------------+------------+\n";
    cout << " | Бічна поверхня циліндра    |" << setw(11) << sb << " |\n";
    cout << " | Повна поверхня циліндра    |" << setw(11) << sp << " |\n";
    cout << " | Об'єм циліндра             |" << setw(11) << v  << " |\n";
    cout << " +----------------------------+------------+\n";
    return 0;
}
