/**
 * @file text.h
 * @brief КПІЗ, частина 4 (варіант 19): опрацювання тексту, групи слів-анаграм.
 *
 * Текст вважається закодованим у UTF-8 (українські та латинські літери).
 * Функції utf8_* та make_anagram_key написано самостійно, без бібліотечних
 * аналогів, оскільки стандартні ctype.h/string.h працюють з байтами, а не
 * з символами Unicode.
 */
#ifndef TEXT_H
#define TEXT_H

#include <stddef.h>
#include <stdint.h>

#define MAX_LINE 255    /**< максимальна довжина рядка тексту (символів) */

/** Динамічний масив рядків (слів або рядків тексту). */
typedef struct {
    char  **items;  /**< масив покажчиків на рядки, виділені в купі */
    size_t  count;  /**< кількість елементів */
    size_t  cap;    /**< місткість масиву    */
} StrList;

/** Статистика тексту. */
typedef struct {
    size_t chars;      /**< кількість символів (кодових точок UTF-8), без '\n' */
    size_t words;      /**< кількість слів */
    size_t sentences;  /**< кількість речень */
} TextStats;

/** Ініціалізує порожній список. */
void strlist_init(StrList *l);

/**
 * Додає копію рядка s у список (розширення через realloc).
 * @return 1 - успішно, 0 - нестача пам'яті
 */
int strlist_add(StrList *l, const char *s);

/** Звільняє всі рядки та сам масив; список стає порожнім. */
void strlist_free(StrList *l);

/**
 * Декодує один символ UTF-8.
 * @param s   покажчик на початок символу
 * @param cp  [out] кодова точка Unicode
 * @return кількість байтів символу (1..4); для некоректного байта - 1 і cp = 0xFFFD
 */
int utf8_decode(const char *s, uint32_t *cp);

/** Кодує кодову точку у UTF-8; повертає кількість записаних байтів (1..4). */
int utf8_encode(uint32_t cp, char *out);

/** Кількість символів (кодових точок) у рядку UTF-8 - власний аналог strlen. */
size_t utf8_strlen(const char *s);

/** Чи є кодова точка літерою (латиниця, кирилиця, у т.ч. українські літери). */
int cp_is_letter(uint32_t cp);

/** Переводить літеру в нижній регістр (латиниця і кирилиця). */
uint32_t cp_to_lower(uint32_t cp);

/**
 * Переводить слово в нижній регістр (UTF-8).
 * @param out буфер розміром не менше strlen(word)+1
 */
void word_to_lower(const char *word, char *out);

/**
 * Будує ключ анаграми: літери слова в нижньому регістрі, впорядковані за
 * зростанням кодів (інші символи, напр. апостроф, ігноруються).
 * Слова є анаграмами тоді й лише тоді, коли їхні ключі однакові.
 * @param out буфер розміром не менше strlen(word)+1
 * @return кількість літер у ключі
 */
size_t make_anagram_key(const char *word, char *out);

/**
 * Перевіряє, чи є два слова анаграмами (розроблено за TDD).
 * Слова, однакові без урахування регістру, анаграмами не вважаються.
 * @return 1 - анаграми, 0 - ні
 */
int is_anagram(const char *w1, const char *w2);

/**
 * Відокремлює слова з рядка за допомогою strtok і додає їх у список.
 * Розділювачі - пропуски та розділові знаки ASCII; на краях слова також
 * відкидаються неалфавітні символи (лапки «», тире тощо).
 * @return кількість доданих слів або (size_t)-1 у разі нестачі пам'яті
 */
size_t split_words(const char *line, StrList *words);

/** Обчислює статистику для масиву рядків тексту. */
TextStats text_stats(const StrList *lines, size_t word_count);

/**
 * Знаходить групи анаграм і друкує їх у потік.
 * Однакові слова (без урахування регістру) враховуються один раз.
 * @param groups_out [out] кількість знайдених груп (може бути NULL)
 * @return 1 - успішно, 0 - нестача пам'яті
 */
int print_anagram_groups(const StrList *words, size_t *groups_out);

/**
 * Будує групи анаграм у вигляді списку рядків "слово1 слово2 ...".
 * Використовується в модульних тестах. Групи впорядковані за ключем.
 * @return 1 - успішно, 0 - нестача пам'яті
 */
int find_anagram_groups(const StrList *words, StrList *groups);

#endif
