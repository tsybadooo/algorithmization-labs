def complexity_chart():
    rows = list(csv.DictReader(open(f'{ROOT}/{K}/reports/complexity.csv', encoding='utf8')))
    data = {'bubble': [], 'quick': []}
    for r in rows:
        data[r['algorithm']].append((int(r['n']), int(r['comparisons'])))
    W, H, L, B, T, Rm = 620, 380, 70, 50, 20, 150
    x0, x1, y0, y1 = 1, 4, 1, 8

    def X(n):
        return L + (math.log10(n) - x0) / (x1 - x0) * (W - L - Rm)

    def Y(v):
        return H - B - (math.log10(v) - y0) / (y1 - y0) * (H - B - T)
    s = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" width="{W}" height="{H}" '
         f'style="font-family:Times New Roman;font-size:12px">']
    for e in range(y0, y1 + 1):
        s.append(f'<line x1="{L}" y1="{Y(10**e):.1f}" x2="{W-Rm}" y2="{Y(10**e):.1f}" stroke="#ddd"/>'
                 f'<text x="{L-6}" y="{Y(10**e)+4:.1f}" text-anchor="end">10<tspan dy="-5" font-size="9">{e}</tspan></text>')
    for e in range(x0, x1 + 1):
        s.append(f'<line x1="{X(10**e):.1f}" y1="{T}" x2="{X(10**e):.1f}" y2="{H-B}" stroke="#ddd"/>'
                 f'<text x="{X(10**e):.1f}" y="{H-B+16}" text-anchor="middle">{10**e}</text>')
    s.append(f'<rect x="{L}" y="{T}" width="{W-L-Rm}" height="{H-B-T}" fill="none" stroke="#000"/>')
    s.append(f'<text x="{(L+W-Rm)/2}" y="{H-12}" text-anchor="middle">розмір масиву n</text>')
    s.append(f'<text x="16" y="{(H-B+T)/2}" text-anchor="middle" transform="rotate(-90 16 {(H-B+T)/2})">кількість порівнянь</text>')
    ns = [10 ** (1 + i * 0.05) for i in range(61)]
    theory = [('n(n−1)/2', [(n, n * (n - 1) / 2) for n in ns], '#c33', '5,4'),
              ('1,39·n·log₂n', [(n, 1.39 * n * math.log2(n)) for n in ns], '#36c', '5,4')]
    for name, pts, col, dash in theory:
        d = ' '.join(f'{X(n):.1f},{Y(v):.1f}' for n, v in pts)
        s.append(f'<polyline points="{d}" fill="none" stroke="{col}" stroke-width="1.2" stroke-dasharray="{dash}"/>')
    for key, col, mark in (('bubble', '#c33', 'circle'), ('quick', '#36c', 'rect')):
        pts = data[key]
        d = ' '.join(f'{X(n):.1f},{Y(v):.1f}' for n, v in pts)
        s.append(f'<polyline points="{d}" fill="none" stroke="{col}" stroke-width="2"/>')
        for n, v in pts:
            if mark == 'circle':
                s.append(f'<circle cx="{X(n):.1f}" cy="{Y(v):.1f}" r="4" fill="{col}"/>')
            else:
                s.append(f'<rect x="{X(n)-4:.1f}" y="{Y(v)-4:.1f}" width="8" height="8" fill="{col}"/>')
    lx = W - Rm + 12
    legend = [('бульбашка (експ.)', '#c33', ''), ('швидке (експ.)', '#36c', ''),
              ('n(n−1)/2 (теор.)', '#c33', '5,4'), ('1,39·n·log₂n (теор.)', '#36c', '5,4')]
    for i, (t, col, dash) in enumerate(legend):
        y = T + 14 + i * 20
        da = f' stroke-dasharray="{dash}"' if dash else ''
        sw = 1.2 if dash else 2
        s.append(f'<line x1="{lx}" y1="{y}" x2="{lx+22}" y2="{y}" stroke="{col}" stroke-width="{sw}"{da}/>'
                 f'<text x="{lx+26}" y="{y+4}">{t}</text>')
    s.append('</svg>')
    return ''.join(s), data


