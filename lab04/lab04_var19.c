/**************************************************************/
/*  Лабораторна робота №4. Індивідуальне завдання, варіант 19. */
/*  Визначити, чи належить точка M(x,y) заштрихованій області. */
/*  Область складається з двох частин:                         */
/*   1) квадрат у I чверті:  0 <= x <= 1,  0 <= y <= 1;        */
/*   2) чверть круга радіуса 1 з центром O(0;0) у III чверті:  */
/*      x <= 0,  y <= 0,  x^2 + y^2 <= 1.                      */
/*  Межі області вважаються такими, що належать їй.            */
/**************************************************************/
#include <stdio.h>
#include "../common_console.h"

int main(void)
{
    console_utf8();
    double x, y;     /* координати точки M */
    int in_square, in_circle;

    printf("Введіть координати точки x y: ");
    if (scanf("%lf%lf", &x, &y) != 2) {
        printf("Помилка: потрібно ввести два числа\n");
        return 1;
    }

    /* Розгалуження оператором if: окремо перевіряємо кожну частину */
    in_square = 0;
    if (x >= 0 && x <= 1 && y >= 0 && y <= 1)
        in_square = 1;

    in_circle = 0;
    if (x <= 0 && y <= 0)
        if (x * x + y * y <= 1)
            in_circle = 1;

    if (in_square || in_circle)
        printf("Точка M(%.3f; %.3f) належить заштрихованій області (%s)\n",
               x, y, in_square ? "квадрат" : "чверть круга");
    else
        printf("Точка M(%.3f; %.3f) не належить заштрихованій області\n", x, y);

    /* Те саме однією умовою з операцією ?: */
    printf("Перевірка операцією ?: -> %s\n",
           ((x >= 0 && x <= 1 && y >= 0 && y <= 1) ||
            (x <= 0 && y <= 0 && x * x + y * y <= 1)) ? "належить" : "не належить");
    return 0;
}
