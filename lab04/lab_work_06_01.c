/*  Визначити, чи належить точка M(x,y) заштрихованій області  */
/*  (два кола, дві трапеції та кут - рис. 1 методички).        */
/*  Замість clrscr()/getch() з conio.h використано стандарт C. */
/**************************************************************/
#include <stdio.h>
#include "../common_console.h"

int main(void)
{
    console_utf8();
    float x, y;   /* координати точки M */
    printf("\n Введіть значення абсциси та ординати: ");
    if (scanf("%f%f", &x, &y) != 2) { printf("Помилка введення\n"); return 1; }

    if ((((x - 3) * (x - 3) + y * y <= 1) && ((x - 3) * (x - 3) + (y + 0.5) * (y + 0.5) >= 0.25)) ||
        ((x >= 5) && (y <= 1) && (x <= 6) && (y >= 2 * x - 12)) ||
        ((x >= 6) && (y <= 1) && (x <= 7) && (y >= -2 * x + 12)) ||
        ((y >= -x + 8) && (y <= 2 * x - 16)))
        printf("\n x=%.2f y=%.2f Точка M(x,y) належить заштрихованій області.\n", x, y);
    else
        printf("\n x=%.2f y=%.2f Точка M(x,y) не належить заштрихованій області.\n", x, y);
    return 0;
}
